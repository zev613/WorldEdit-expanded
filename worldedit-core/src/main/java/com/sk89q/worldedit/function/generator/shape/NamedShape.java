package com.sk89q.worldedit.function.generator.shape;

import com.google.common.collect.ImmutableList;
import com.sk89q.worldedit.math.Vector3;

import java.util.List;
import java.util.Locale;

import static com.google.common.base.Preconditions.checkNotNull;

/**
 * A shape that can be generated by name, such as {@code heart} or {@code gyroid}.
 */
public abstract class NamedShape {

    private final String name;
    private final List<String> aliases;
    private final String category;
    private final String description;
    private final List<ShapeParameter> parameters;

    protected NamedShape(String name, List<String> aliases, String category, String description,
                         List<ShapeParameter> parameters) {
        this.name = checkNotNull(name).toLowerCase(Locale.ROOT);
        this.aliases = aliases.stream().map(a -> a.toLowerCase(Locale.ROOT)).collect(ImmutableList.toImmutableList());
        this.category = checkNotNull(category);
        this.description = checkNotNull(description);
        this.parameters = ImmutableList.copyOf(parameters);
    }

    public String getName() {
        return name;
    }

    public List<String> getAliases() {
        return aliases;
    }

    public String getCategory() {
        return category;
    }

    public String getDescription() {
        return description;
    }

    public List<ShapeParameter> getParameters() {
        return parameters;
    }

    /**
     * Whether this shape was defined by a user rather than built in.
     *
     * @return true for user-defined shapes
     */
    public boolean isCustom() {
        return false;
    }

    /**
     * Create an instance of this shape.
     *
     * @param parameters the parameter values
     * @param radii the size of the shape in blocks along x, y and z
     * @return the instance
     */
    public abstract ShapeInstance create(ShapeParameters parameters, Vector3 radii);
}
