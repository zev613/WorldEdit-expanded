package com.sk89q.worldedit.function.generator.shape;

import com.google.common.collect.ImmutableList;
import com.sk89q.worldedit.internal.util.LogManagerCompat;
import org.apache.logging.log4j.Logger;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.regex.Pattern;

/**
 * All shapes that can be generated by name: the built-in ones plus presets
 * saved by players.
 *
 * <p>Presets are stored one per line in a plain text file as
 * {@code name = shape setting=value ...}.</p>
 */
public final class ShapeLibrary {

    private static final Logger LOGGER = LogManagerCompat.getLogger();
    private static final Pattern VALID_NAME = Pattern.compile("[a-z0-9_-]{1,32}");

    private final Map<String, NamedShape> builtins = new LinkedHashMap<>();
    private final Map<String, PresetShape> presets = new LinkedHashMap<>();
    private final Path presetFile;

    /**
     * Create a library.
     *
     * @param presetFile where presets are saved, or null to keep them in memory only
     */
    public ShapeLibrary(Path presetFile) {
        this.presetFile = presetFile;
        List<NamedShape> shapes = BuiltinShapes.create();
        for (NamedShape shape : shapes) {
            builtins.put(shape.getName(), shape);
        }
        for (NamedShape shape : shapes) {
            for (String alias : shape.getAliases()) {
                builtins.putIfAbsent(alias, shape);
            }
        }
        load();
    }

    /**
     * Whether a name can be used for a preset.
     *
     * @param name the name
     * @return true if valid
     */
    public static boolean isValidName(String name) {
        return VALID_NAME.matcher(name).matches();
    }

    /**
     * Find a shape or preset by name or alias, ignoring case.
     *
     * @param name the name
     * @return the shape, if any
     */
    public synchronized Optional<NamedShape> find(String name) {
        String key = name.toLowerCase(Locale.ROOT);
        NamedShape shape = builtins.get(key);
        if (shape == null) {
            shape = presets.get(key);
        }
        return Optional.ofNullable(shape);
    }

    /**
     * The built-in shapes, without duplicates for aliases.
     *
     * @return the shapes
     */
    public synchronized List<NamedShape> getBuiltins() {
        return builtins.values().stream().distinct().collect(ImmutableList.toImmutableList());
    }

    /**
     * The saved presets, sorted by name.
     *
     * @return the presets
     */
    public synchronized List<PresetShape> getPresets() {
        return presets.values().stream().sorted(Comparator.comparing(NamedShape::getName))
            .collect(ImmutableList.toImmutableList());
    }

    /**
     * All names that can be typed, for tab completion.
     *
     * @return the names
     */
    public synchronized List<String> getAllNames() {
        List<String> names = new ArrayList<>(builtins.keySet());
        names.addAll(presets.keySet());
        names.sort(null);
        return names;
    }

    /**
     * Save a preset.
     *
     * @param name the preset name
     * @param baseName the shape (or preset) it is based on
     * @param arguments the settings
     * @return the new preset
     * @throws IllegalArgumentException if the name or settings are invalid
     */
    public synchronized PresetShape savePreset(String name, String baseName, List<String> arguments) {
        String key = name.toLowerCase(Locale.ROOT);
        if (!isValidName(key)) {
            throw new IllegalArgumentException("Preset names can use letters, digits, _ and -, up to 32 characters");
        }
        if (builtins.containsKey(key)) {
            throw new IllegalArgumentException("'" + key + "' is a built-in shape; pick another name");
        }
        NamedShape base = find(baseName)
            .orElseThrow(() -> new IllegalArgumentException("Unknown shape '" + baseName + "'"));
        List<String> settings = new ArrayList<>();
        if (base instanceof PresetShape preset) {
            // start from that preset's settings, then apply the new ones
            settings.addAll(preset.getSettingArguments());
            base = preset.getBase();
        }
        settings.addAll(arguments);
        PresetShape created = new PresetShape(key, base, settings);
        // store the fully-resolved settings so the file is easy to read
        created = new PresetShape(key, base, created.getSettingArguments());
        presets.put(key, created);
        save();
        return created;
    }

    /**
     * Delete a preset.
     *
     * @param name the preset name
     * @return true if it existed
     */
    public synchronized boolean deletePreset(String name) {
        boolean removed = presets.remove(name.toLowerCase(Locale.ROOT)) != null;
        if (removed) {
            save();
        }
        return removed;
    }

    private void load() {
        if (presetFile == null || !Files.isRegularFile(presetFile)) {
            return;
        }
        try {
            for (String line : Files.readAllLines(presetFile, StandardCharsets.UTF_8)) {
                String trimmed = line.trim();
                if (trimmed.isEmpty() || trimmed.startsWith("#")) {
                    continue;
                }
                int eq = trimmed.indexOf('=');
                if (eq <= 0) {
                    continue;
                }
                String name = trimmed.substring(0, eq).trim().toLowerCase(Locale.ROOT);
                String[] parts = trimmed.substring(eq + 1).trim().split("\\s+");
                if (parts.length == 0 || parts[0].isEmpty() || !isValidName(name) || builtins.containsKey(name)) {
                    continue;
                }
                NamedShape base = builtins.get(parts[0].toLowerCase(Locale.ROOT));
                if (base == null) {
                    LOGGER.warn("Ignoring shape preset {}: unknown shape {}", name, parts[0]);
                    continue;
                }
                try {
                    presets.put(name, new PresetShape(name, base, Arrays.asList(parts).subList(1, parts.length)));
                } catch (IllegalArgumentException e) {
                    LOGGER.warn("Ignoring shape preset {}: {}", name, e.getMessage());
                }
            }
        } catch (IOException e) {
            LOGGER.warn("Failed to read shape presets from " + presetFile, e);
        }
    }

    private void save() {
        if (presetFile == null) {
            return;
        }
        List<String> lines = new ArrayList<>();
        lines.add("# Shape presets for //shape. Each line is: name = shape setting=value ...");
        lines.add("# Manage them in game with //shapedef save|delete|list");
        for (PresetShape preset : getPresets()) {
            lines.add(preset.getName() + " = " + preset.getBase().getName() + " "
                + String.join(" ", preset.getSettingArguments()));
        }
        try {
            Path parent = presetFile.getParent();
            if (parent != null) {
                Files.createDirectories(parent);
            }
            Files.write(presetFile, lines, StandardCharsets.UTF_8);
        } catch (IOException e) {
            LOGGER.warn("Failed to save shape presets to " + presetFile, e);
        }
    }
}
